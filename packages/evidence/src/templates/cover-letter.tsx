import React from "react";
import { evidenceTypeLabel, formatDate, formatMoney, reasonLabel } from "../model.js";
import type { PackExhibit, PackInput, TimelineRow } from "../types.js";

function Cite({ ids }: { ids: string[] }) {
  return <span className="cite">[{ids.join(", ")}]</span>;
}

/** Statement text: B's cited claims when present, otherwise the note PayPal receives. */
function Statement({ input }: { input: PackInput }) {
  const n = input.narrative;
  if (n && n.claims.length)
    return (
      <div className="statement">
        <p>
          <strong>{n.headline}</strong>
        </p>
        <ol>
          {n.claims.map((claim, i) => (
            <li key={i}>
              {claim.text} <Cite ids={claim.exhibits} />
            </li>
          ))}
        </ol>
      </div>
    );
  return (
    <div className="statement">
      <p className="pre">{input.note}</p>
    </div>
  );
}

export function CoverLetter({
  input,
  exhibits,
  timeline,
}: {
  input: PackInput;
  exhibits: PackExhibit[];
  timeline: TimelineRow[];
}) {
  const order = exhibits.find((x) => x.evidence.data["kind"] === "order")?.evidence.data;
  const orderId =
    (typeof order?.["orderId"] === "string" && order["orderId"]) ||
    input.transactionContext?.order?.id ||
    null;
  const facts: [string, React.ReactNode][] = [
    ["PayPal dispute ID", <span className="mono">{input.paypalDisputeId}</span>],
    ["Transaction ID", <span className="mono">{input.sellerTransactionId ?? "—"}</span>],
    [
      "Order / invoice",
      <span className="mono">{[orderId, input.invoiceNumber].filter(Boolean).join(" / ") || "—"}</span>,
    ],
    ["Disputed amount", formatMoney(input.amountCents, input.currency)],
    ["Dispute reason", reasonLabel(input.reason)],
    ["Dispute stage", input.stage.replaceAll("_", " ").toLowerCase()],
    ["Dispute opened", formatDate(input.paypalCreatedAt)],
    ["Response due", formatDate(input.sellerResponseDueAt)],
  ];
  return (
    <article>
      <header className="letterhead">
        <div>
          <div className="merchant">{input.merchant.name}</div>
          <div className="muted">Seller response to PayPal dispute {input.paypalDisputeId}</div>
        </div>
        <div className="muted mono">Prepared {formatDate(input.generatedAt)}</div>
      </header>

      <h1>Seller statement and evidence</h1>
      <p className="muted">
        The seller contests this dispute. Each statement below cites the exhibit that supports it. All
        exhibits are reproduced from the seller&apos;s own records and follow this letter in order.
      </p>

      <h2>Dispute facts</h2>
      <table className="facts">
        <tbody>
          {facts.map(([k, v]) => (
            <tr key={k}>
              <th scope="row">{k}</th>
              <td>{v}</td>
            </tr>
          ))}
        </tbody>
      </table>

      <h2>Statement</h2>
      <Statement input={input} />

      <h2>Timeline</h2>
      {timeline.length ? (
        <table>
          <thead>
            <tr>
              <th style={{ width: "28%" }}>Date (UTC)</th>
              <th style={{ width: "24%" }}>Event</th>
              <th>Detail</th>
              <th style={{ width: "12%" }}>Exhibit</th>
            </tr>
          </thead>
          <tbody>
            {timeline.map((row, i) => (
              <tr key={i}>
                <td className="mono">{formatDate(row.at)}</td>
                <td>{row.label}</td>
                <td>{row.detail || "—"}</td>
                <td className="cite">{row.exhibitId ?? ""}</td>
              </tr>
            ))}
          </tbody>
        </table>
      ) : (
        <p className="muted">No dated records were available to build a timeline.</p>
      )}

      <h2>Exhibit index</h2>
      {exhibits.length ? (
        <table>
          <thead>
            <tr>
              <th style={{ width: "10%" }}>Exhibit</th>
              <th style={{ width: "30%" }}>Record</th>
              <th style={{ width: "20%" }}>PayPal evidence type</th>
              <th>What it shows</th>
            </tr>
          </thead>
          <tbody>
            {exhibits.map((x) => (
              <tr key={x.exhibitId}>
                <td className="cite">{x.exhibitId}</td>
                <td>{x.heading}</td>
                <td>{evidenceTypeLabel(x.evidence.type)}</td>
                <td>{x.summary}</td>
              </tr>
            ))}
          </tbody>
        </table>
      ) : (
        <p className="muted">No exhibits are attached.</p>
      )}
      <p className="footnote">
        Generated by the seller&apos;s dispute desk from order, shipping, listing and message records. Times
        are UTC. Customer IP addresses are partially masked.
      </p>
    </article>
  );
}
